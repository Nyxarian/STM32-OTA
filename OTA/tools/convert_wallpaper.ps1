param(
    [string]$SourceImage = (Join-Path (Split-Path -Parent $PSScriptRoot) 'Assets\brand-logo.png'),
    [string]$OutputFile = (Join-Path (Split-Path -Parent $PSScriptRoot) 'MDK-ARM\UI\ui_wallpaper.c')
)

Add-Type -AssemblyName System.Drawing

$screenWidth = 320
$screenHeight = 240
$logoMaxWidth = 160
$logoMaxHeight = 120

if (-not (Test-Path -LiteralPath $SourceImage)) {
    throw "Source image was not found: $SourceImage"
}

$source = [System.Drawing.Bitmap]::new($SourceImage)
$canvas = [System.Drawing.Bitmap]::new(
    $screenWidth,
    $screenHeight,
    [System.Drawing.Imaging.PixelFormat]::Format24bppRgb
)
$graphics = [System.Drawing.Graphics]::FromImage($canvas)

try {
    $graphics.Clear([System.Drawing.Color]::Black)
    $graphics.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
    $graphics.PixelOffsetMode = [System.Drawing.Drawing2D.PixelOffsetMode]::HighQuality
    $graphics.CompositingQuality = [System.Drawing.Drawing2D.CompositingQuality]::HighQuality

    # Fit the complete logo inside the LCD instead of cropping it.
    $scale = [Math]::Min($logoMaxWidth / $source.Width, $logoMaxHeight / $source.Height)
    $drawWidth = [Math]::Round($source.Width * $scale)
    $drawHeight = [Math]::Round($source.Height * $scale)
    $drawX = [Math]::Floor(($screenWidth - $drawWidth) / 2)
    $drawY = [Math]::Floor(($screenHeight - $drawHeight) / 2)

    $graphics.DrawImage($source, $drawX, $drawY, $drawWidth, $drawHeight)

    $outputDirectory = Split-Path -Parent $OutputFile
    New-Item -ItemType Directory -Path $outputDirectory -Force | Out-Null
    $utf8NoBom = [System.Text.UTF8Encoding]::new($false)
    $writer = [System.IO.StreamWriter]::new($OutputFile, $false, $utf8NoBom)

    try {
        $writer.WriteLine('/* Generated by tools/convert_wallpaper.ps1. Do not edit manually. */')
        $writer.WriteLine('#include "ui_wallpaper.h"')
        $writer.WriteLine()
        $writer.WriteLine('static const uint8_t ui_wallpaper_data[] = {')

        for ($y = 0; $y -lt $screenHeight; $y++) {
            $line = [System.Text.StringBuilder]::new('    ')

            for ($x = 0; $x -lt $screenWidth; $x++) {
                $pixel = $canvas.GetPixel($x, $y)
                # Cast before shifting so RGB565 red and green bits do not overflow as bytes.
                $red = [int]$pixel.R
                $green = [int]$pixel.G
                $blue = [int]$pixel.B
                $rgb565 = (($red -shr 3) -shl 11) -bor (($green -shr 2) -shl 5) -bor ($blue -shr 3)
                [void]$line.AppendFormat('0x{0:X2}, 0x{1:X2}, ', ($rgb565 -band 0xFF), (($rgb565 -shr 8) -band 0xFF))
            }

            $writer.WriteLine($line.ToString())
        }

        $writer.WriteLine('};')
        $writer.WriteLine()
        $writer.WriteLine('const lv_image_dsc_t ui_wallpaper = {')
        $writer.WriteLine('    .header.magic = LV_IMAGE_HEADER_MAGIC,')
        $writer.WriteLine('    .header.cf = LV_COLOR_FORMAT_RGB565,')
        $writer.WriteLine('    .header.w = 320,')
        $writer.WriteLine('    .header.h = 240,')
        $writer.WriteLine('    .header.stride = 320 * 2,')
        $writer.WriteLine('    .data_size = sizeof(ui_wallpaper_data),')
        $writer.WriteLine('    .data = ui_wallpaper_data,')
        $writer.WriteLine('};')
    }
    finally {
        $writer.Dispose()
    }
}
finally {
    $graphics.Dispose()
    $canvas.Dispose()
    $source.Dispose()
}
